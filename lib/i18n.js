export function t(locale, key) {
  return dict[locale]?.[key] ?? dict.ar[key] ?? key;
}

// Pick the localized field of a data record, falling back to the other language.
export function loc(locale, obj, field) {
  if (!obj) return "";
  if (locale === "ar") return obj[field + "Ar"] || obj[field] || "";
  return obj[field] || obj[field + "Ar"] || "";
}

export function fmtSAR(locale, n) {
  return new Intl.NumberFormat(locale === "ar" ? "ar-SA" : "en-US").format(n) + " " + t(locale, "sar");
}
